def test_allowlist_serving_requires_opt_in(
    lists_app: Flask, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    output = tmp_path / "users" / "sam" / "output"
    sync_published_allowlist(output, WHITELIST, enabled=True, generated_at=GENERATED_AT)
    recorded: dict[str, object] = {}

    def capture(**kwargs: object) -> None:
        recorded.update(kwargs)

    monkeypatch.setattr(Analytics, "record_request", capture)
    published = {"value": False}

    def lookup(_username: str) -> StubUser:
        return StubUser(output, published["value"])

    monkeypatch.setattr(User, "get_by_username", lookup)
    monkeypatch.setattr(
        SystemConfig, "is_allowlist_published", staticmethod(lambda: False)
    )

    client = lists_app.test_client()
    hidden = client.get("/u/sam/allowlist.txt?format=adblock")
    assert hidden.status_code == 404

    published["value"] = True
    adblock = client.get("/u/sam/allowlist.txt?format=adblock")
    assert adblock.status_code == 200
    assert adblock.headers["X-Format"] == "adblock"
    assert "X-Domain-Count" not in adblock.headers
    body = adblock.get_data(as_text=True)
    assert "@@||ads.example.com^" in body
    assert recorded["list_type"] == Analytics.TYPE_ALLOWLIST
    assert recorded["list_name"] == ALLOWLIST_NAME

    omitted = client.get("/u/sam/allowlist.txt")
    assert omitted.status_code == 200
    assert "@@||cdn.example.com^" in omitted.get_data(as_text=True)

    plain = client.get("/u/sam/allowlist.txt?format=plain")
    assert plain.status_code == 200
    assert _rules(plain.get_data(as_text=True)) == ["example.com"]

    hosts = client.get("/u/sam/allowlist.txt?format=hosts")
    assert hosts.status_code == 404

    default_output = tmp_path / "default" / "output"
    sync_published_allowlist(
        default_output, WHITELIST, enabled=True, generated_at=GENERATED_AT
    )
    default_hidden = client.get("/lists/allowlist.txt?format=adblock")
    assert default_hidden.status_code == 404

    monkeypatch.setattr(
        SystemConfig, "is_allowlist_published", staticmethod(lambda: True)
    )
    default_list = client.get("/lists/allowlist.txt?format=adblock")
    assert default_list.status_code == 200
    assert "@@||ads.example.com^" in default_list.get_data(as_text=True)
    assert isinstance(default_list, Response)
