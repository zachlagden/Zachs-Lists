def test_validate_domain_accepts_subdomain_prefix() -> None:
    assert validate_domain("example.com")
    assert validate_domain("*.example.com")
    assert validate_domain("@@example.com")
    assert not validate_domain("@@*.example.com")
    assert not validate_domain("@@localhost")
    assert not validate_domain("@@example.local")
    assert not validate_domain("localhost")


def test_validate_whitelist_accepts_all_pattern_types() -> None:
    errors = validate_whitelist(WHITELIST)
    assert errors == []
    assert validate_whitelist("@@not a domain") == ["Line 1: Invalid domain"]
    assert validate_whitelist("@@*.example.com") == ["Line 1: Invalid domain"]
    assert validate_whitelist("/[/") == ["Line 1: Invalid regex pattern"]


def test_conversion_covers_every_whitelist_pattern() -> None:
    adblock = render_allowlist(WHITELIST, "adblock", GENERATED_AT)
    plain = render_allowlist(WHITELIST, "plain", GENERATED_AT)

    assert "Allowlist generated by lists.zachlagden.uk" in adblock
    assert "Generated: 2026-11-14T12:00:00Z" in adblock
    assert "Pi-hole v6" in adblock
    assert "apex" in adblock
    assert "#   *.cdn.example.com" in adblock
    assert "#   ads.*.example.com" in adblock
    assert "pihole --allow-regex" in adblock
    assert "#   /^banner\\.example\\.com$/" in adblock
    assert _rules(adblock) == [
        "example.com",
        "@@||ads.example.com^",
        "@@||cdn.example.com^",
    ]
    for rule in _rules(adblock):
        assert "$" not in rule
        assert "*" not in rule
        if rule.startswith("@@"):
            assert rule.startswith("@@||")
            assert rule.endswith("^")
            assert rule.count("|") == 2

    assert "exact domains only" in plain
    assert "does not honor subdomain semantics" in plain
    assert _rules(plain) == ["example.com"]
    assert "@@||" not in "\n".join(_rules(plain))
    with pytest.raises(ValueError):
        render_allowlist(WHITELIST, "hosts", GENERATED_AT)


def test_generator_host_follows_the_public_url() -> None:
    assert host_from_public_url("https://lists.example.test") == "lists.example.test"
    assert host_from_public_url("https://lists.example.test:8443/app") == (
        "lists.example.test:8443"
    )
    assert host_from_public_url("http://localhost:5173") == "localhost:5173"
    assert host_from_public_url(None) == BLOCKLIST_GENERATOR_HOST
    assert host_from_public_url("   ") == BLOCKLIST_GENERATOR_HOST
    rendered = render_allowlist(
        "example.com\n", "adblock", GENERATED_AT, "lists.example.test"
    )
    assert "Allowlist generated by lists.example.test" in rendered
    assert BLOCKLIST_GENERATOR_HOST not in rendered


def test_format_negotiation() -> None:
    assert allowlist_format(None) == "adblock"
    assert allowlist_format("adblock") == "adblock"
    assert allowlist_format("plain") == "plain"
    assert allowlist_format("hosts") is None
    assert blocklist_format(None) == "hosts"
    assert blocklist_format("adblock") == "adblock"
    assert blocklist_format("nope") == "hosts"


def test_publishing_is_opt_in(tmp_path: Path) -> None:
    sync_published_allowlist(
        tmp_path, WHITELIST, enabled=False, generated_at=GENERATED_AT
    )
    assert list(tmp_path.iterdir()) == []

    planted = tmp_path / "allowlist_hosts.txt.gz"
    planted.write_bytes(b"stale")
    (tmp_path / "allowlist_adblock.txt.gz").write_bytes(b"stale")
    sync_published_allowlist(
        tmp_path, WHITELIST, enabled=False, generated_at=GENERATED_AT
    )
    assert not planted.exists()
    assert list(tmp_path.iterdir()) == []

    sync_published_allowlist(
        tmp_path, WHITELIST, enabled=True, generated_at=GENERATED_AT
    )
    assert _rules(_read_gz(tmp_path / "allowlist_adblock.txt.gz"))[0] == "example.com"
    assert "@@||cdn.example.com^" in _read_gz(tmp_path / "allowlist_adblock.txt.gz")
    assert _rules(_read_gz(tmp_path / "allowlist_plain.txt.gz")) == ["example.com"]
    assert not (tmp_path / "allowlist_hosts.txt.gz").exists()
    assert not (tmp_path / "allowlist_hosts.txt").exists()


